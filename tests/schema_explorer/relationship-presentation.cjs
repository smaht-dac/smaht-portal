const fs = require('node:fs'), assert = require('node:assert/strict');
(async () => {
 const source = fs.readFileSync('src/encoded/static/components/static-pages/schema-explorer/relationship-presentation.js', 'utf8');
 const { relationshipPresentation: present } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
 const index = { models: [{ name: 'VariantCalls', fields: [{ name: 'reference_genome', schema: { title: 'Reference Genome', description: 'Reference genome used for alignment' } }] }] };
 const edge = { from: 'VariantCalls', to: 'ReferenceGenome', field: 'reference_genome', kind: 'linkTo' };
 const summary = present([edge], index)[0];
 assert.equal(summary.title, 'Genome reference');
 assert.match(summary.meaning, /does not establish coordinate compatibility/);
 assert.equal(summary.description, index.models[0].fields[0].schema.description);
 assert.equal(summary.field, edge.field);
 assert.equal(summary.multiple, false);
 assert.deepEqual(present([edge, { ...edge, from: 'AlignedReads' }], index)[0].from, ['VariantCalls', 'AlignedReads']);
 const reverse = present([{ ...edge, kind: 'reverse' }], index)[0];
 assert.equal(reverse.meaning, summary.description, 'Reverse relationships retain model wording rather than a direct-reference interpretation');
 assert.equal(present([{ ...edge, field: 'future_links[]' }], index)[0].multiple, true);
 const unknown = present([{ ...edge, field: 'future_link' }], index)[0];
 assert.equal(unknown.meaning, '', 'Unknown roles must not invent explanations');
 assert.equal(unknown.title, 'future link');
 const assembly = present([{ from: 'DonorSpecificAssembly', field: 'derived_from[]', to: 'File', kind: 'linkTo' }], index)[0];
 assert.equal(assembly.title, 'Assembly input provenance');
 assert.match(assembly.meaning, /direct input provenance/);
 assert.match(assembly.meaning, /does not encode the processing steps/);
 assert.equal(assembly.multiple, true);
 const nested = present([{ from: 'WorkflowRun', field: 'input_files[].format_if_extra', to: 'FileFormat', kind: 'linkTo' }], index)[0];
 assert.notEqual(nested.title, 'Workflow inputs', 'Do not confuse a nested format reference with an input file');
 const target = present([{ ...edge, to: 'FutureGenome' }], index)[0];
 assert.equal(target.meaning, summary.description, 'Unrecognized targets keep the authoritative model description');
 console.log('Relationship presentation: scientific scope, assembly provenance, compact metadata, grouping and safe fallbacks passed.');
})();
