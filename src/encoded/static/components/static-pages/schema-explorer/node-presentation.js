const tones = {
    blue: '#5c83a7', teal: '#5c9288', purple: '#8b79a7', amber: '#b39359', neutral: '#8a99a8', abstract: '#9480af',
};
const stageTones = {
    Donors: 'blue', 'Clinical context': 'teal', 'Clinical details': 'teal', Collection: 'amber',
    'Source material': 'teal', Culture: 'teal', Samples: 'blue', Pathology: 'purple',
    'Analyte preparation': 'teal', Analytes: 'teal', 'Library preparation': 'blue', Libraries: 'blue', Sequencing: 'purple', Outputs: 'purple',
    Definitions: 'blue', Execution: 'teal', Analysis: 'purple',
    'Acquired data': 'blue', 'Processed data': 'teal', Results: 'purple', Quality: 'amber',
    Organization: 'blue', Submission: 'teal', Knowledge: 'purple',
};
export function stageAccent(stage, isAbstract = false) {
    return tones[isAbstract || stage === 'Base types' ? 'abstract' : stageTones[stage] || 'neutral'];
}
function shortCaption(value) {
    const text = value.replace(/\s+/g, ' ').trim().replace(/[.!]$/, '');
    if (text.length <= 32) return text;
    const prefix = text.slice(0, 31);
    const lastSpace = prefix.lastIndexOf(' ');
    return `${lastSpace > 17 ? prefix.slice(0, lastSpace) : prefix}…`;
}
export function nodePresentation(name, model, { isAbstract = false } = {}) {
    const description = typeof model?.schema?.description === 'string' ? model.schema.description.trim() : '';
    const title = typeof model?.schema?.title === 'string' ? model.schema.title : '';
    const role = model ? roles[name] || description || title || 'Schema definition' : 'Unresolved schema';
    return { caption: shortCaption(role), description: description || role, isAbstract };
}
